//! Test engine runtime: the suite/test/hook registry and the at-exit runner
//! exposed to generated tyrus programs through a C ABI. Imported in tyrus as
//! `tyrus:test`.
//!
//! The registry is filled during program startup: `describe` callbacks run
//! synchronously at registration time (pushing a suite frame in which `test`
//! and the hooks register), exactly like Jest. Nothing runs yet. The suites are
//! executed by an at-exit handler armed on the first registration, so a program
//! is free to keep `main` entirely empty in test mode.
//!
//! # The wrapper ABI
//!
//! Registration hands the runtime two pointers per closure:
//!
//! * a *wrapper* `unsafe extern "C" fn(*mut TyrusTestResult, *mut c_void) -> i32`
//!   generated by the compiler. The wrapper installs a catch context, invokes
//!   the closure, and converts an unwound `throw` into `status` + a cloned
//!   `message`; the async rejection path is a settled promise, so the wrapper
//!   never has to unwind across a C boundary.
//! * a *closure context* and its drop function, reusing the promise closure
//!   contract (`{ function, environment }` freed by
//!   `tyrus_drop_promise_closure_context`).
//!
//! This keeps every generated-code boundary on the generated side of
//! `setjmp`/`longjmp`: no `longjmp` ever crosses into a Rust frame, where it
//! would be undefined behavior.

use crate::promise::{TYRUS_PROMISE_REJECTED, TyrusPromise, wait_until_settled};
use std::ffi::c_void;
use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Mutex, OnceLock};
use tyrus_string::TyrusString;

fn assertion_failures() -> &'static Mutex<Vec<String>> {
    static FAILURES: OnceLock<Mutex<Vec<String>>> = OnceLock::new();
    FAILURES.get_or_init(|| Mutex::new(Vec::new()))
}

#[unsafe(no_mangle)]
pub extern "C" fn tyrus_test_begin_assertions() {
    assertion_failures().lock().unwrap().clear();
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_record_assertion_failure(message: TyrusString, offset: u64) {
    unsafe {
        let detail = format_assertion_failure(message.as_str(), offset as usize);
        assertion_failures().lock().unwrap().push(detail);
    }
}

fn take_assertion_failures() -> Option<String> {
    let mut failures = assertion_failures().lock().unwrap();
    if failures.is_empty() {
        return None;
    }
    let count = failures.len();
    let details = failures.drain(..).collect::<Vec<_>>().join("\n");
    Some(format!("__tyrus_assertions__:{count}\n{details}"))
}

fn format_assertion_failure(message: &str, offset: usize) -> String {
    let Some(source) = std::env::var_os("TYRUS_TEST_SOURCE").map(std::path::PathBuf::from) else {
        return message.to_string();
    };
    let Ok(contents) = std::fs::read_to_string(&source) else {
        return message.to_string();
    };
    let offset = offset.min(contents.len());
    let prefix = &contents[..offset];
    let line = prefix.bytes().filter(|byte| *byte == b'\n').count() + 1;
    let column = prefix
        .rsplit('\n')
        .next()
        .map_or(0, |line| line.chars().count())
        + 1;
    let display = std::env::current_dir()
        .ok()
        .and_then(|cwd| source.strip_prefix(cwd).ok().map(Path::to_path_buf))
        .unwrap_or_else(|| source.clone());
    let location = format!("{}:{line}:{column}", display.display());
    format!("{location} {message}")
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Mode {
    Normal,
    Skip,
    Only,
}

impl Mode {
    /// The `describe` ABI's mode argument: 0 plain, 1 `.skip`, 2 `.only`.
    fn from_describe(mode: i32) -> Self {
        match mode {
            1 => Mode::Skip,
            2 => Mode::Only,
            _ => Mode::Normal,
        }
    }
}

struct TestClosure {
    name: Option<String>,
    mode: Mode,
    wrapper: unsafe extern "C" fn(*mut TyrusTestResult, *mut c_void) -> i32,
    context: *mut c_void,
    drop_context: unsafe extern "C" fn(*mut c_void),
}

impl Drop for TestClosure {
    fn drop(&mut self) {
        if !self.context.is_null() {
            unsafe { (self.drop_context)(self.context) };
        }
    }
}

unsafe impl Send for TestClosure {}

#[derive(Clone, Copy)]
enum Entry {
    Test(usize),
    Suite(usize),
    Todo(usize),
}

struct SuiteNode {
    name: String,
    parent: usize,
    mode: Mode,
    todos: Vec<String>,
    entries: Vec<Entry>,
    tests: Vec<TestClosure>,
    before_all: Vec<TestClosure>,
    after_all: Vec<TestClosure>,
    before_each: Vec<TestClosure>,
    after_each: Vec<TestClosure>,
    children: Vec<usize>,
    setup_error: Option<String>,
}

#[derive(Default)]
struct TestState {
    suites: Vec<SuiteNode>,
    current: usize,
}

impl TestState {
    fn root() -> Self {
        Self {
            suites: vec![SuiteNode {
                name: String::new(),
                parent: usize::MAX,
                mode: Mode::Normal,
                todos: Vec::new(),
                entries: Vec::new(),
                tests: Vec::new(),
                before_all: Vec::new(),
                after_all: Vec::new(),
                before_each: Vec::new(),
                after_each: Vec::new(),
                children: Vec::new(),
                setup_error: None,
            }],
            current: 0,
        }
    }
}

fn state() -> &'static Mutex<TestState> {
    static STATE: OnceLock<Mutex<TestState>> = OnceLock::new();
    STATE.get_or_init(|| Mutex::new(TestState::root()))
}

#[repr(C)]
pub struct TyrusTestResult {
    pub status: i32,
    pub message: TyrusString,
    pub promise: *mut TyrusPromise,
}

impl Default for TyrusTestResult {
    fn default() -> Self {
        Self {
            status: 0,
            message: TyrusString::null(),
            promise: std::ptr::null_mut(),
        }
    }
}

unsafe fn take_result_message(result: &mut TyrusTestResult) -> Option<String> {
    unsafe {
        if result.message.is_null() {
            return None;
        }
        let message = std::mem::replace(&mut result.message, TyrusString::null());
        let text = message.as_str().to_string();
        message.release();
        Some(text)
    }
}

unsafe fn invoke_closure(closure: &TestClosure) -> Result<(), String> {
    let mut result = TyrusTestResult::default();
    unsafe {
        let status = (closure.wrapper)(&mut result, closure.context);
        let message = take_result_message(&mut result);
        if status != 0 {
            if !result.promise.is_null() {
                crate::promise::tyrus_promise_free(result.promise);
            }
            return Err(message.unwrap_or_else(|| "test threw".to_string()));
        }
        let promise = result.promise;
        if !promise.is_null() {
            let settled = wait_until_settled(promise);
            if settled == TYRUS_PROMISE_REJECTED {
                let error = crate::promise::tyrus_promise_error_message(promise);
                let text = if error.is_null() {
                    "test rejected asynchronously".to_string()
                } else {
                    error.as_str().to_string()
                };
                crate::promise::tyrus_promise_free(promise);
                return Err(text);
            }
            crate::promise::tyrus_promise_free(promise);
        }
        if let Some(failures) = take_assertion_failures() {
            return Err(failures);
        }
        Ok(())
    }
}

fn boot() {
    static BOOTED: AtomicBool = AtomicBool::new(false);
    if BOOTED.swap(true, Ordering::SeqCst) {
        return;
    }
    extern "C" fn run_at_exit() {
        let failed = unsafe { crate::test::run_registered_suites() };
        if failed {
            crate::print_lock::flush_stdout();
            unsafe { libc::_exit(1) };
        }
    }
    unsafe { libc::atexit(run_at_exit) };
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_describe(
    name: TyrusString,
    wrapper: unsafe extern "C" fn(*mut TyrusTestResult, *mut c_void) -> i32,
    context: *mut c_void,
    drop_context: unsafe extern "C" fn(*mut c_void),
) {
    unsafe { tyrus_test_describe_mode(0, name, wrapper, context, drop_context) };
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_describe_mode(
    mode: i32,
    name: TyrusString,
    wrapper: unsafe extern "C" fn(*mut TyrusTestResult, *mut c_void) -> i32,
    context: *mut c_void,
    drop_context: unsafe extern "C" fn(*mut c_void),
) {
    boot();
    let text = if name.is_null() {
        "describe".to_string()
    } else {
        unsafe { name.as_str() }.to_string()
    };
    let (parent, id) = {
        let mut guard = state()
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        let parent = guard.current;
        let id = guard.suites.len();
        guard.suites.push(SuiteNode {
            name: text.clone(),
            parent,
            mode: Mode::from_describe(mode),
            todos: Vec::new(),
            entries: Vec::new(),
            tests: Vec::new(),
            before_all: Vec::new(),
            after_all: Vec::new(),
            before_each: Vec::new(),
            after_each: Vec::new(),
            children: Vec::new(),
            setup_error: None,
        });
        guard.suites[parent].children.push(id);
        guard.suites[parent].entries.push(Entry::Suite(id));
        guard.current = id;
        (parent, id)
    };

    let callback_error = {
        let mut result = TyrusTestResult::default();
        let status = unsafe { wrapper(&mut result, context) };
        let message = unsafe { take_result_message(&mut result) };
        if status != 0 {
            Some(message.unwrap_or_else(|| "describe callback threw".to_string()))
        } else {
            None
        }
    };
    if !context.is_null() {
        unsafe { (drop_context)(context) };
    }

    let mut guard = state()
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    guard.current = parent;
    if let Some(error) = callback_error {
        guard.suites[id].setup_error = Some(error);
    }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_register(
    kind: i32,
    name: TyrusString,
    wrapper: unsafe extern "C" fn(*mut TyrusTestResult, *mut c_void) -> i32,
    context: *mut c_void,
    drop_context: unsafe extern "C" fn(*mut c_void),
) {
    boot();
    let display = if name.is_null() {
        None
    } else {
        Some(unsafe { name.as_str() }.to_string())
    };
    let closure = TestClosure {
        name: display,
        mode: match kind {
            5 => Mode::Skip,
            6 => Mode::Only,
            _ => Mode::Normal,
        },
        wrapper,
        context,
        drop_context,
    };
    let mut guard = state()
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let current = guard.current;
    let suite = &mut guard.suites[current];
    match kind {
        0 | 5 | 6 => {
            suite.entries.push(Entry::Test(suite.tests.len()));
            suite.tests.push(closure);
        }
        1 => suite.before_all.push(closure),
        2 => suite.after_all.push(closure),
        3 => suite.before_each.push(closure),
        4 => suite.after_each.push(closure),
        _ => {
            panic!("tyrus runtime error: unknown test registration kind {kind}");
        }
    }
}

fn color_from_env() -> bool {
    match std::env::var("TYRUS_TEST_COLOR").ok().as_deref() {
        Some("always") => true,
        Some("never") => false,
        _ => {
            std::env::var_os("NO_COLOR").is_none() && crate::print_lock::tyrus_stdout_is_terminal()
        }
    }
}

struct Palette {
    color: bool,
}

impl Palette {
    fn paint(&self, code: &str, text: &str) -> String {
        if self.color {
            format!("\u{1b}[{code}m{text}\u{1b}[0m")
        } else {
            text.to_string()
        }
    }

    fn green(&self, text: &str) -> String {
        self.paint("32", text)
    }

    fn red(&self, text: &str) -> String {
        self.paint("31", text)
    }

    fn dim(&self, text: &str) -> String {
        self.paint("2", text)
    }

    fn bold(&self, text: &str) -> String {
        self.paint("1", text)
    }

    fn summary_count(&self, count: u32, color: &str) -> String {
        let text = count.to_string();
        if count == 0 {
            text
        } else {
            self.paint(&format!("1;{color}"), &text)
        }
    }
}

fn format_duration(elapsed: std::time::Duration) -> String {
    let millis = elapsed.as_secs_f64() * 1000.0;
    if millis < 1000.0 {
        format!("{millis:.0}ms")
    } else {
        format!("{:.2}s", elapsed.as_secs_f64())
    }
}

struct Runner {
    palette: Palette,
    passed: u32,
    failed: u32,
    skipped: u32,
    todo: u32,
    out: String,
}

impl Runner {
    fn line(&mut self, indent: usize, text: &str) {
        for _ in 0..indent {
            self.out.push_str("  ");
        }
        self.out.push_str(text);
        self.out.push('\n');
    }

    fn flush(&mut self) {
        if self.out.is_empty() {
            return;
        }
        crate::print_lock::tyrus_stdout_lock_begin();
        crate::print_lock::write_stdout(&self.out);
        crate::print_lock::tyrus_stdout_lock_end();
        self.out.clear();
    }
}

#[derive(Clone, Copy, PartialEq, Eq)]
enum Status {
    Run,
    Skip,
    Hidden,
}

struct Selection {
    tests: Vec<Vec<Status>>,
    todos: Vec<Vec<bool>>,
    visible: Vec<bool>,
    runnable: Vec<bool>,
    skipped: u32,
    todo: u32,
    has_only: bool,
}

#[derive(Clone, Copy, Default)]
struct Inherited {
    skip: bool,
    focused: bool,
}

fn select(state: &TestState) -> Selection {
    let has_only = state.suites.iter().any(|suite| {
        suite.mode == Mode::Only || suite.tests.iter().any(|test| test.mode == Mode::Only)
    });
    let count = state.suites.len();
    let mut selection = Selection {
        tests: vec![Vec::new(); count],
        todos: vec![Vec::new(); count],
        visible: vec![false; count],
        runnable: vec![false; count],
        skipped: 0,
        todo: 0,
        has_only,
    };
    visit_selection(state, 0, Inherited::default(), &mut selection);
    selection
}

fn visit_selection(
    state: &TestState,
    id: usize,
    inherited: Inherited,
    selection: &mut Selection,
) -> (bool, bool) {
    let suite = &state.suites[id];
    let inherited = Inherited {
        skip: inherited.skip || suite.mode == Mode::Skip,
        focused: inherited.focused || suite.mode == Mode::Only,
    };

    let mut visible = false;
    let mut runnable = false;
    let mut statuses = Vec::with_capacity(suite.tests.len());
    for test in &suite.tests {
        let focused = inherited.focused || test.mode == Mode::Only;
        let status = if inherited.skip || test.mode == Mode::Skip {
            Status::Skip
        } else if selection.has_only && !focused {
            Status::Hidden
        } else {
            Status::Run
        };
        match status {
            Status::Run => {
                runnable = true;
                visible = true;
            }
            Status::Skip => {
                visible = true;
                selection.skipped += 1;
            }
            Status::Hidden => selection.skipped += 1,
        }
        statuses.push(status);
    }
    selection.tests[id] = statuses;

    let mut todos = Vec::with_capacity(suite.todos.len());
    for _ in &suite.todos {
        let listed = !selection.has_only || inherited.focused;
        if listed {
            visible = true;
            selection.todo += 1;
        }
        todos.push(listed);
    }
    selection.todos[id] = todos;

    for child in &suite.children {
        let (child_visible, child_runnable) = visit_selection(state, *child, inherited, selection);
        visible |= child_visible;
        runnable |= child_runnable;
    }

    selection.visible[id] = visible;
    selection.runnable[id] = runnable;
    (visible, runnable)
}

struct EachHooks<'a> {
    before: Vec<&'a TestClosure>,
    after: Vec<&'a TestClosure>,
}

/// Runs everything the program registered and reports it, returning whether
/// anything failed.
///
/// Ordering within a suite is Jest's: `beforeAll`, then the suite's own tests,
/// then nested suites, then `afterAll`. The previous version ran nested suites
/// *first*, which reported a child's tests before its parent's and, worse, ran
/// them before the parent's `beforeAll` had set anything up.
pub unsafe fn run_registered_suites() -> bool {
    let state = {
        let mut guard = state()
            .lock()
            .unwrap_or_else(std::sync::PoisonError::into_inner);
        std::mem::replace(&mut *guard, TestState::root())
    };

    if !has_any_registration(&state) {
        return false;
    }

    let selection = select(&state);
    let total: usize = selection
        .tests
        .iter()
        .map(|flags| {
            flags
                .iter()
                .filter(|status| **status == Status::Run)
                .count()
        })
        .sum();

    let mut runner = Runner {
        palette: Palette {
            color: color_from_env(),
        },
        passed: 0,
        failed: 0,
        skipped: 0,
        todo: 0,
        out: String::new(),
    };

    let plural = if total == 1 { "test" } else { "tests" };
    runner.line(0, &format!("Running {total} {plural}..."));
    runner.line(0, "");

    let started = std::time::Instant::now();
    unsafe { run_suite(&state, 0, 0, &selection, &mut runner) };
    let elapsed = started.elapsed();

    runner.skipped += selection.skipped;
    runner.todo = selection.todo;
    runner.line(0, "");

    let mut summary = format!(
        "{} passed, {} failed",
        runner.palette.summary_count(runner.passed, "32"),
        runner.palette.summary_count(runner.failed, "31")
    );
    if runner.skipped > 0 {
        summary.push_str(&format!(
            ", {} skipped",
            runner.palette.summary_count(runner.skipped, "33")
        ));
    }
    if runner.todo > 0 {
        summary.push_str(&format!(
            ", {} todo",
            runner.palette.summary_count(runner.todo, "90")
        ));
    }
    summary.push_str(&format!(" ({:.2}s)", elapsed.as_secs_f64()));
    runner.line(0, &summary);
    runner.flush();
    write_report(&runner);

    drop(state);
    runner.failed > 0
}

fn write_report(runner: &Runner) {
    let Some(path) = std::env::var_os("TYRUS_TEST_REPORT") else {
        return;
    };
    let line = format!(
        "{} {} {} {}\n",
        runner.passed, runner.failed, runner.skipped, runner.todo
    );
    if let Err(error) = std::fs::write(&path, line) {
        eprintln!("warning: could not write the test report: {error}");
    }
}

fn has_any_registration(state: &TestState) -> bool {
    state.suites.len() > 1
        || !state.suites[0].tests.is_empty()
        || !state.suites[0].todos.is_empty()
        || !state.suites[0].before_all.is_empty()
        || !state.suites[0].after_all.is_empty()
        || !state.suites[0].before_each.is_empty()
        || !state.suites[0].after_each.is_empty()
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_settle(promise: *mut TyrusPromise) -> i32 {
    if promise.is_null() {
        return -1;
    }
    unsafe { wait_until_settled(promise) }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_rejection_message(promise: *const TyrusPromise) -> TyrusString {
    if promise.is_null() {
        return TyrusString::literal("");
    }
    let message = unsafe { crate::promise::tyrus_promise_error_message(promise) };
    if message.is_null() {
        TyrusString::literal("")
    } else {
        message
    }
}

#[unsafe(no_mangle)]
pub unsafe extern "C" fn tyrus_test_todo(name: TyrusString) {
    boot();
    let text = if name.is_null() {
        "todo".to_string()
    } else {
        unsafe { name.as_str() }.to_string()
    };
    let mut guard = state()
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner);
    let current = guard.current;
    let suite = &mut guard.suites[current];
    suite.entries.push(Entry::Todo(suite.todos.len()));
    suite.todos.push(text);
}

fn ancestors(state: &TestState, id: usize) -> Vec<usize> {
    let mut chain = Vec::new();
    let mut cursor = id;
    loop {
        chain.push(cursor);
        let parent = state.suites[cursor].parent;
        if parent == usize::MAX {
            break;
        }
        cursor = parent;
    }
    chain.reverse();
    chain
}

fn each_hooks(state: &TestState, id: usize) -> EachHooks<'_> {
    let chain = ancestors(state, id);
    let mut before: Vec<&TestClosure> = Vec::new();
    for suite in &chain {
        before.extend(state.suites[*suite].before_each.iter());
    }
    let mut after: Vec<&TestClosure> = Vec::new();
    for suite in chain.iter().rev() {
        after.extend(state.suites[*suite].after_each.iter());
    }
    EachHooks { before, after }
}

unsafe fn run_suite(
    state: &TestState,
    id: usize,
    depth: usize,
    selection: &Selection,
    runner: &mut Runner,
) {
    if !selection.visible[id] {
        return;
    }

    let suite = &state.suites[id];
    let named = !suite.name.is_empty();
    if named {
        let header = runner.palette.bold(&suite.name);
        runner.line(depth, &header);
    }
    let inner = if named { depth + 1 } else { depth };
    let running_here = selection.tests[id]
        .iter()
        .filter(|status| **status == Status::Run)
        .count() as u32;

    if let Some(error) = &suite.setup_error {
        let label = runner.palette.red("✗");
        runner.line(inner, &format!("{label} {} (describe failed)", suite.name));
        let detail = runner.palette.red(error);
        runner.line(inner + 1, &detail);
        runner.failed += running_here.max(1);
        return;
    }

    runner.flush();
    let runnable = selection.runnable[id];
    if runnable && let Err(message) = unsafe { run_hooks(&suite.before_all) } {
        report_suite_hook_failure(runner, inner, &suite.name, "beforeAll", &message);
        runner.failed += running_here;
        return;
    }

    let hooks = each_hooks(state, id);
    for entry in &suite.entries {
        match *entry {
            Entry::Test(index) => match selection.tests[id][index] {
                Status::Run => unsafe { run_one_test(&suite.tests[index], &hooks, inner, runner) },
                Status::Skip => {
                    let name = suite.tests[index].name.as_deref().unwrap_or("unnamed");
                    let line = runner.palette.dim(&format!("○ {name} (skipped)"));
                    runner.line(inner, &line);
                }
                Status::Hidden => {}
            },
            Entry::Todo(index) => {
                if selection.todos[id][index] {
                    let line = runner
                        .palette
                        .dim(&format!("○ {} (todo)", suite.todos[index]));
                    runner.line(inner, &line);
                }
            }
            Entry::Suite(child) => unsafe { run_suite(state, child, inner, selection, runner) },
        }
    }

    if runnable && let Err(message) = unsafe { run_hooks(&suite.after_all) } {
        report_suite_hook_failure(runner, inner, &suite.name, "afterAll", &message);
        runner.failed += 1;
    }
    runner.flush();
}

fn report_suite_hook_failure(
    runner: &mut Runner,
    indent: usize,
    suite: &str,
    hook: &str,
    message: &str,
) {
    let label = runner.palette.red("✗");
    let display = if suite.is_empty() { "<root>" } else { suite };
    runner.line(indent, &format!("{label} {display} ({hook} failed)"));
    let detail = runner.palette.red(message);
    runner.line(indent + 1, &detail);
}

unsafe fn run_hooks(hooks: &[TestClosure]) -> Result<(), String> {
    for hook in hooks {
        unsafe { invoke_closure(hook) }?;
    }
    Ok(())
}

unsafe fn run_one_test(
    test: &TestClosure,
    hooks: &EachHooks<'_>,
    indent: usize,
    runner: &mut Runner,
) {
    let display = test.name.as_deref().unwrap_or("unnamed").to_string();
    runner.flush();
    let started = std::time::Instant::now();

    let mut failure = None;
    for hook in &hooks.before {
        if let Err(message) = unsafe { invoke_closure(hook) } {
            failure = Some(format!("beforeEach: {message}"));
            break;
        }
    }
    if failure.is_none()
        && let Err(message) = unsafe { invoke_closure(test) }
    {
        failure = Some(message);
    }
    for hook in &hooks.after {
        if let Err(message) = unsafe { invoke_closure(hook) } {
            match &mut failure {
                Some(current) => current.push_str(&format!("; afterEach: {message}")),
                None => failure = Some(format!("afterEach: {message}")),
            }
            break;
        }
    }

    let elapsed = started.elapsed();
    match failure {
        Some(message) => {
            runner.failed += 1;
            let label = runner.palette.red("✗");
            let (assertion_count, details) = message
                .strip_prefix("__tyrus_assertions__:")
                .and_then(|message| message.split_once('\n'))
                .and_then(|(count, details)| {
                    count.parse::<usize>().ok().map(|count| (count, details))
                })
                .unwrap_or((0, message.as_str()));
            let suffix = if assertion_count == 0 {
                String::new()
            } else {
                format!(
                    " ({assertion_count} assertion failure{})",
                    if assertion_count == 1 { "" } else { "s" }
                )
            };
            runner.line(indent, &format!("{label} {display}{suffix}"));
            for detail in details.lines() {
                runner.line(indent + 1, &runner.palette.red(detail));
            }
        }
        None => {
            runner.passed += 1;
            let label = runner.palette.green("✓");
            let timing = if elapsed.as_millis() >= 1 {
                runner
                    .palette
                    .dim(&format!(" {}", format_duration(elapsed)))
            } else {
                String::new()
            };
            runner.line(indent, &format!("{label} {display}{timing}"));
        }
    }
    runner.flush();
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn summary_counts_color_only_nonzero_values() {
        let palette = Palette { color: true };
        assert_eq!(palette.summary_count(3, "32"), "\u{1b}[1;32m3\u{1b}[0m");
        assert_eq!(palette.summary_count(0, "31"), "0");
        assert_eq!(palette.summary_count(2, "33"), "\u{1b}[1;33m2\u{1b}[0m");
        assert_eq!(palette.summary_count(1, "90"), "\u{1b}[1;90m1\u{1b}[0m");
    }

    #[test]
    fn assertion_failures_keep_each_detail_on_its_own_line() {
        let message = "__tyrus_assertions__:2\nfirst\nsecond";
        let (count, details) = message
            .strip_prefix("__tyrus_assertions__:")
            .and_then(|message| message.split_once('\n'))
            .unwrap();
        assert_eq!(count, "2");
        assert_eq!(details.lines().collect::<Vec<_>>(), vec!["first", "second"]);
    }
}
